//! Generates the asset table from the lockfile.
//!
//! `include_bytes!` needs a literal path, so an asset's stored path is fixed at
//! compile time and cannot be looked up at runtime. A packaged binary must run with
//! no source checkout — the standalone-artifact requirement — so a runtime directory
//! scan is not an option either.
//!
//! Hand-maintaining hash paths in Rust source would mean the same address written in
//! three places: the lockfile, the source, and the Nix check. Duplicated lists drift.
//! So the lockfile is the single source of truth and this script derives the rest,
//! which is what the lockfile already claims to be.
//!
//! The derivation here must match `src/address.rs` exactly. It is repeated rather
//! than imported because a build script cannot depend on the crate it builds, and
//! `address_matches_the_build_script` in the crate's tests asserts the two agree.

use std::path::Path;

/// Kept in step with `address::ALGORITHM`.
const ALGORITHM: &str = "sha256";
/// Kept in step with `address::ADDRESS_HEX_LEN`.
const ADDRESS_HEX_LEN: usize = 16;

fn main() {
    let manifest = std::env::var("CARGO_MANIFEST_DIR").expect("cargo sets the manifest directory");
    let assets = Path::new(&manifest).join("assets");
    let lockfile_path = assets.join("vendor.lock.json");

    // Rerun when the lockfile changes, or the generated table would describe a runtime
    // the project no longer pins.
    println!("cargo:rerun-if-changed={}", lockfile_path.display());

    let text = std::fs::read_to_string(&lockfile_path)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", lockfile_path.display()));
    let lockfile: serde_json::Value = serde_json::from_str(&text)
        .unwrap_or_else(|e| panic!("{} is malformed: {e}", lockfile_path.display()));

    let mut own = Vec::new();
    let mut vendored = Vec::new();

    for file in lockfile["own"].as_array().into_iter().flatten() {
        let path = field(file, "path");
        let digest = field(file, "sha256");
        // The template is pinned and not stored: it is the document `init` produces
        // rather than an asset copied beside it.
        if file.get("stored").and_then(serde_json::Value::as_bool) == Some(false) {
            continue;
        }
        own.push(entry(&path, &digest, &assets));
    }

    for library in lockfile["libraries"].as_array().into_iter().flatten() {
        for file in library["files"].as_array().into_iter().flatten() {
            let path = field(file, "path");
            let digest = field(file, "sha256");
            vendored.push(entry(&path, &digest, &assets));
        }
    }

    assert!(!own.is_empty(), "the lockfile records no own assets");
    assert!(
        !vendored.is_empty(),
        "the lockfile records no vendored assets"
    );

    let generated = format!(
        "// Generated by build.rs from assets/vendor.lock.json. Do not edit.\n\
         //\n\
         // Each asset's path is its content address, derived from the digest the\n\
         // lockfile records. Editing this file by hand would put an address in a\n\
         // second place, which is what the generation exists to prevent.\n\
         \n\
         /// This project's own assets, at their content addresses.\n\
         pub const OWN: &[Asset] = &[\n{}];\n\
         \n\
         /// The vendored browser-side runtime, at its content addresses.\n\
         pub const VENDORED: &[Asset] = &[\n{}];\n",
        own.join(""),
        vendored.join("")
    );

    let out = std::env::var("OUT_DIR").expect("cargo sets the output directory");
    let destination = Path::new(&out).join("assets.rs");
    std::fs::write(&destination, generated)
        .unwrap_or_else(|e| panic!("cannot write {}: {e}", destination.display()));
}

/// One `Asset` literal, with its stored path and an `include_bytes!` of its source.
///
/// The bytes are embedded from the addressed copy, so a build cannot succeed against
/// an address the store does not hold.
fn entry(recorded_path: &str, digest: &str, assets: &Path) -> String {
    let name = recorded_path.rsplit('/').next().unwrap_or(recorded_path);
    let stored = format!("{ALGORITHM}-{}/{name}", &digest[..ADDRESS_HEX_LEN]);
    let source = assets.join(&stored);

    assert!(
        source.is_file(),
        "the lockfile records {recorded_path} at {stored}, and no such file is stored. Run the \
         store population step before building"
    );
    println!("cargo:rerun-if-changed={}", source.display());

    // The include path is relative to the generated file's includer, so it is
    // absolute here: OUT_DIR is not a fixed distance from the assets directory.
    format!(
        "    Asset {{\n        path: {stored:?},\n        bytes: include_bytes!({:?}),\n    }},\n",
        source.display().to_string()
    )
}

fn field(value: &serde_json::Value, name: &str) -> String {
    value[name]
        .as_str()
        .unwrap_or_else(|| panic!("a lockfile entry has no {name}: {value}"))
        .to_owned()
}
